public class AssignmentOperater {
    static void main() {
        int i=10;
        i+=5;
        System.out.println(i);
        i-=50;
        System.out.println(i);
        i*=90;
        System.out.println(i);
        i/=2;
        System.out.println(i);
        i%=2;
        System.out.println(i);
    }
}
