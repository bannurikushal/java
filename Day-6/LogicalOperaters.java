public class LogicalOperaters {
    static void main() {
        int a=4;
        int b=9;
        //and operater
        System.out.println((a<b)&&(a>b));
        System.out.println((a<b)&&(a<b));
        //or operater
        System.out.println((a<b)||(a>b));
        //not operater
        System.out.println(!(a<b));
    }
}
