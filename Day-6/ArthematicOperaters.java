public class ArthematicOperaters {
    public static void main(String ars[]){
        int a=10;
        int b=20;
        System.out.println("sum="+(a+b));
        System.out.println("sub="+(a-b));
        System.out.println("mul="+(a*b));
        System.out.println("div="+(a/b));
        System.out.println("mod="+(a%b));
    }
}
